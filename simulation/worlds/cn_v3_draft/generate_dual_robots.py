#!/usr/bin/env python3
"""Generate the Fortress V3 field and props with the BR/TR video-v2 prototypes."""

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET


HERE = Path(__file__).resolve().parent
DEFAULT_OUTPUT = HERE / 'worlds' / 'robocon_cn_v3_draft_tr_br.world'


def generate(output):
    tree = ET.parse(HERE / 'source' / 'initial_objects.world')
    world = tree.getroot().find('world')
    world.set('name', 'robocon_cn_v3_draft_tr_br')

    # These footprint poses were measured on the V3 floor with the actual wheels.
    for name, pose in (
        ('robocon_tr_video_v2',
         '-5.15 -5.116825928 0.025100001 0 0 1.5707963267948966'),
        ('robocon_br_video_v2',
         '-4.35 -5.166075008 0.030625772 0 0 1.5707963267948966'),
    ):
        include = ET.SubElement(world, 'include')
        ET.SubElement(include, 'uri').text = f'model://{name}'
        ET.SubElement(include, 'name').text = name
        ET.SubElement(include, 'pose').text = pose

    tree.getroot().insert(0, ET.Comment(
        ' Generated by generate_dual_robots.py; edit the source or generator. '))
    output.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(tree, space='  ')
    tree.write(output, encoding='utf-8', xml_declaration=True)
    print(f'Generated Fortress BR/TR scene: {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT,
                        help='world file to write')
    generate(parser.parse_args().output)
